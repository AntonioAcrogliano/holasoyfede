import type { CustomScorerId, Difficulty, Game, GameType, ScorerConfig, Theme } from "../types";
import { pat } from "./patterns";
import { guides } from "./guides";

const t = (
  bg: string,
  accent: string,
  ink: string,
  pattern: string | undefined,
  icon: string,
  accentFont?: string
): Theme => ({ bg, accent, ink, pattern, icon, accentFont });

const custom = (id: CustomScorerId): ScorerConfig => ({ kind: "custom", id });
const COUNTER: ScorerConfig = { kind: "counter" };
const ROUNDS: ScorerConfig = { kind: "rounds" };
const TEAMS: ScorerConfig = { kind: "teams" };

type Extra = { scorer?: ScorerConfig; notes?: string; requires?: string };

// Juego con ficha completa (la guía se suma desde ./guides por slug).
function g(
  slug: string,
  name: string,
  min: number,
  max: number,
  type: GameType,
  categories: string[],
  difficulty: Difficulty,
  minutes: number | null,
  description: string,
  theme: Theme,
  extra: Extra = {}
): Game {
  return {
    slug,
    name,
    players: { min, max },
    type,
    categories,
    difficulty,
    minutes,
    description,
    status: "completo",
    theme,
    ...guides[slug],
    ...extra,
  };
}

// Ficha básica: en estos NO se inventan reglas.
const basicThemes: [string, string, string][] = [
  ["#EADCC6", "#C8643B", "#3B2F2A"],
  ["#DDE2C8", "#7A8450", "#33361F"],
  ["#F0D9C0", "#A9713F", "#3B2F2A"],
  ["#E3D5CA", "#8C5E58", "#3B2F2A"],
  ["#D8E0DC", "#5E7F78", "#27332F"],
];
const basicPatterns = [pat.dots, pat.diamonds, pat.crosses, pat.planks, pat.confetti];

function basic(
  slug: string,
  name: string,
  description: string,
  icon: string,
  categories: string[] = [],
  more: Partial<Game> = {}
): Game {
  const i = [...slug].reduce((a, c) => a + c.charCodeAt(0), 0);
  const [bg, accent, ink] = basicThemes[i % basicThemes.length];
  return {
    slug,
    name,
    players: { min: null, max: null },
    type: null,
    categories,
    difficulty: null,
    minutes: null,
    description,
    status: "falta-info",
    theme: t(bg, accent, ink, basicPatterns[i % basicPatterns.length](accent + "30"), icon),
    ...more,
  };
}

